import { pgTable, serial, text, integer, boolean, timestamp, jsonb } from 'drizzle-orm/pg-core'

export const targets = pgTable('targets', {
  id: serial('id').primaryKey(),
  name: text('name').notNull(),
  url: text('url').notNull(),
  type: text('type').notNull().default('http'),
  method: text('method').notNull().default('GET'),
  interval: integer('interval').notNull().default(60),
  timeout: integer('timeout').notNull().default(30),
  retries: integer('retries').notNull().default(0),
  tags: jsonb('tags').$type<string[]>().notNull().default([]),
  enabled: boolean('enabled').notNull().default(true),
  maxRedirects: integer('max_redirects').notNull().default(10),
  ignoreTls: boolean('ignore_tls').notNull().default(false),
  upsideDown: boolean('upside_down').notNull().default(false),
  description: text('description'),
  notificationIds: jsonb('notification_ids').$type<string[]>().default([]),
  dockerContainer: text('docker_container'),
  pushToken: text('push_token'),
  steamGameId: text('steam_game_id'),
  jsonQuery: text('json_query'),
  expectedValue: text('expected_value'),
  proxyId: text('proxy_id'),
  resendNotification: boolean('resend_notification').notNull().default(false),
  notificationInterval: integer('notification_interval'),
  notificationThreshold: integer('notification_threshold'),
  createdAt: timestamp('created_at').defaultNow().notNull(),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
})
